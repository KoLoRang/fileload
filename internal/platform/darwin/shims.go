//go:build darwin

package darwin

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"sync"

	"fileload/internal/platform"
)

const (
	blockStart = "# >>> fileload >>>"
	blockEnd   = "# <<< fileload <<<"
)

// shims writes one executable sh script per command into bin and keeps a
// marked block in the shell profiles that puts bin at the FRONT of PATH.
// The block stays after unmount (scripts print a hint when FileLoad is not
// running); only the scripts come and go with the mount.
type shims struct {
	bin      string
	profiles []string
	mu       sync.Mutex
}

func (s *shims) BinDir() string { return s.bin }

func (s *shims) Install(specs []platform.ShimSpec) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := os.MkdirAll(s.bin, 0o700); err != nil {
		return err
	}
	keep := map[string]bool{}
	for _, sp := range specs {
		keep[sp.Name] = true
	}
	s.removeLocked(keep)
	for _, sp := range specs {
		if err := os.WriteFile(filepath.Join(s.bin, sp.Name), []byte(script(sp)), 0o755); err != nil {
			return err
		}
	}
	for _, p := range s.profiles {
		if err := ensureBlock(p, s.bin); err != nil {
			return fmt.Errorf("更新 %s 失败: %w", p, err)
		}
	}
	return nil
}

func (s *shims) Remove() error {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.removeLocked(nil)
	return nil
}

// removeLocked deletes generated scripts (recognised by their header).
func (s *shims) removeLocked(keep map[string]bool) {
	ents, err := os.ReadDir(s.bin)
	if err != nil {
		return
	}
	for _, e := range ents {
		if e.IsDir() || keep[e.Name()] {
			continue
		}
		p := filepath.Join(s.bin, e.Name())
		if head, err := os.ReadFile(p); err == nil && bytes.Contains(head, []byte(scriptMark)) {
			_ = os.Remove(p)
		}
	}
}

const scriptMark = "# Generated by FileLoad."

// script cd-s into the remote dir matching $PWD (inside the mount) or the
// mount root, through the local proxy that holds the credentials.
func script(sp platform.ShimSpec) string {
	host, port, _ := strings.Cut(sp.ProxyAddr, ":")
	q := platform.BashQuote
	return fmt.Sprintf(`#!/bin/sh
%s Do not edit; regenerated on every mount.
PROXY_HOST=%s
PROXY_PORT=%s
SRV_USER=%s
MNT=%s
ROOT=%s
LINE=%s

rp="$ROOT"
case "$PWD/" in
  "$MNT"/*)
    sub="${PWD#"$MNT"}"
    sub="${sub#/}"
    [ -n "$sub" ] && rp="$ROOT/$sub"
    ;;
esac

if ! nc -z "$PROXY_HOST" "$PROXY_PORT" >/dev/null 2>&1; then
  echo "[fileload] 本地代理未运行：请先启动 FileLoad 并挂载" >&2
  exit 1
fi

qrp=$(printf '%%s' "$rp" | sed "s/'/'\\\\''/g")
exec ssh -p "$PROXY_PORT" -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null \
  -o LogLevel=ERROR -o ServerAliveInterval=30 -t "$SRV_USER@$PROXY_HOST" "cd '$qrp' && $LINE"
`, scriptMark, q(host), q(port), q(sp.User), q(sp.Target), q(sp.Root), q(sp.RemoteLine))
}

// ensureBlock adds (or refreshes) the PATH block in profile.
func ensureBlock(profile, bin string) error {
	data, err := os.ReadFile(profile)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	block := fmt.Sprintf("%s\nexport PATH=%s:\"$PATH\"\n%s\n", blockStart, platform.BashQuote(bin), blockEnd)
	text := string(data)
	if i := strings.Index(text, blockStart); i >= 0 {
		if j := strings.Index(text[i:], blockEnd); j >= 0 {
			end := i + j + len(blockEnd)
			if end < len(text) && text[end] == '\n' {
				end++
			}
			if text[i:end] == block {
				return nil
			}
			text = text[:i] + block + text[end:]
			return os.WriteFile(profile, []byte(text), 0o644)
		}
	}
	if text != "" && !strings.HasSuffix(text, "\n") {
		text += "\n"
	}
	return os.WriteFile(profile, []byte(text+block), 0o644)
}
