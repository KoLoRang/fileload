// shims writes <name>.cmd (ASCII stub) + <name>.ps1 (logic, UTF-8 BOM) per
// command into bin and keeps bin at the FRONT of the user PATH, so it wins
// against same-named tools (e.g. Qt's rcc.exe inside anaconda).
type shims struct {
	bin string
	mu  sync.Mutex
}

func (s *shims) BinDir() string { return s.bin }

func (s *shims) Install(specs []platform.ShimSpec) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := os.MkdirAll(s.bin, 0o700); err != nil {
		return err
	}
	keep := map[string]bool{}
	for _, sp := range specs {
		keep[strings.ToLower(sp.Name+".cmd")] = true
		keep[strings.ToLower(sp.Name+".ps1")] = true
	}
	removeWrappers(s.bin, keep)
	for _, sp := range specs {
		if err := os.WriteFile(filepath.Join(s.bin, sp.Name+".cmd"), []byte(cmdStub(sp.Name)), 0o755); err != nil {
			return err
		}
		ps := append([]byte{0xEF, 0xBB, 0xBF}, psScript(sp)...)
		if err := os.WriteFile(filepath.Join(s.bin, sp.Name+".ps1"), ps, 0o755); err != nil {
			return err
		}
	}
	if err := prependUserPath(s.bin); err != nil {
		return fmt.Errorf("PATH 更新失败: %w", err)
	}
	broadcastEnvChange()
	return nil
}

func (s *shims) Remove() error {
	s.mu.Lock()
	defer s.mu.Unlock()
	removeWrappers(s.bin, nil)
	err := removeFromUserPath(s.bin)
	broadcastEnvChange()
	return err
}

// removeWrappers deletes generated *.cmd / *.ps1 except keep (lower-case).
func removeWrappers(bin string, keep map[string]bool) {
	ents, err := os.ReadDir(bin)
	if err != nil {
		return
	}
	for _, e := range ents {
		n := strings.ToLower(e.Name())
		if e.IsDir() || keep[n] || !(strings.HasSuffix(n, ".cmd") || strings.HasSuffix(n, ".ps1")) {
			continue
		}
		_ = os.Remove(filepath.Join(bin, e.Name()))
	}
}

// cmdStub is pure ASCII (no codepage issues) and delegates to the .ps1.
func cmdStub(name string) string {
	var b strings.Builder
	b.WriteString("@echo off\n")
	b.WriteString("rem Generated by FileLoad. Do not edit; it is regenerated on every mount.\n")
	b.WriteString("where ssh >nul 2>&1 || (echo [fileload] ssh not found - install Windows OpenSSH client & exit /b 1)\n")
	fmt.Fprintf(&b, "powershell -NoProfile -ExecutionPolicy Bypass -File \"%%~dp0%s.ps1\" %%*\n", name)
	b.WriteString("exit /b %ERRORLEVEL%\n")
	return b.String()
}

func psq(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

// psScript connects through the local proxy (which holds the credentials)
// and cd-s into the remote dir matching the current directory.
func psScript(sp platform.ShimSpec) string {
	host, port, _ := strings.Cut(sp.ProxyAddr, ":")
	var b strings.Builder
	b.WriteString("# Generated by FileLoad. Do not edit; regenerated on every mount.\n")
	fmt.Fprintf(&b, "$proxyHost = %s\n$proxyPort = %s\n$srvUser = %s\n$drive = %s\n$root = %s\n$remoteLine = %s\n",
		psq(host), psq(port), psq(sp.User), psq(sp.Target), psq(sp.Root), psq(sp.RemoteLine))
	b.WriteString(`
$sshArgs = @("-p", "$proxyPort", "-o", "StrictHostKeyChecking=no",
    "-o", "UserKnownHostsFile=NUL", "-o", "LogLevel=ERROR", "-o", "ServerAliveInterval=30",
    "-t", "$srvUser@$proxyHost")

# Start in the mount dir; on the FileLoad drive use the matching remote sub dir.
$rp = $root
$cwd = $PWD.Path
if ($cwd.Length -ge 2 -and $cwd.Substring(0, 2).ToLower() -eq $drive.ToLower()) {
    $sub = $cwd.Substring(2).Replace('\', '/').Trim('/')
    if ($sub) { $rp = "$root/$sub" }
}
$cmd = "cd '" + $rp.Replace("'", "'\''") + "' && " + $remoteLine
# Windows PowerShell 5.1 does not escape embedded double quotes for native commands
if ($PSVersionTable.PSVersion.Major -lt 7) { $cmd = $cmd.Replace('"', '\"') }

$tcp = Test-NetConnection -ComputerName $proxyHost -Port $proxyPort -InformationLevel Quiet -WarningAction SilentlyContinue
if (-not $tcp) {
    Write-Host "[fileload] 本地代理未运行：请先启动 FileLoad 并挂载" -ForegroundColor Yellow
    exit 1
}
& ssh @sshArgs $cmd
exit $LASTEXITCODE
`)
	return b.String()
}

// ---- user PATH (HKCU\Environment) ----

// readUserPath reads the RAW value (no %VAR% expansion) and its type.
// GetBinaryValue cannot be used: it fails on REG_SZ/REG_EXPAND_SZ.
func readUserPath() (string, uint32, error) {
	k, err := registry.OpenKey(registry.CURRENT_USER, `Environment`, registry.QUERY_VALUE)
	if err != nil {
		return "", 0, err
	}
	defer k.Close()
	cur, typ, err := k.GetStringValue("Path")
	if errors.Is(err, registry.ErrNotExist) {
		return "", registry.NONE, nil
	}
	return cur, typ, err
}

func writeUserPath(v string, typ uint32) error {
	k, err := registry.OpenKey(registry.CURRENT_USER, `Environment`, registry.SET_VALUE)
	if err != nil {
		return err
	}
	defer k.Close()
	if typ == registry.EXPAND_SZ {
		return k.SetExpandStringValue("Path", v)
	}
	return k.SetStringValue("Path", v)
}

func prependUserPath(dir string) error {
	cur, typ, err := readUserPath()
	if err != nil {
		return err
	}
	for part := range strings.SplitSeq(cur, ";") {
		if strings.EqualFold(strings.TrimSpace(part), dir) {
			return nil
		}
	}
	nv := dir
	if t := strings.TrimSuffix(strings.TrimRight(cur, " \t"), ";"); t != "" {
		nv = dir + ";" + t
	}
	if typ == registry.NONE {
		typ = registry.EXPAND_SZ
	}
	return writeUserPath(nv, typ)
}

func removeFromUserPath(dir string) error {
	cur, typ, err := readUserPath()
	if err != nil || cur == "" {
		return err
	}
	var kept []string
	removed := false
	for part := range strings.SplitSeq(cur, ";") {
		switch {
		case strings.EqualFold(strings.TrimSpace(part), dir):
			removed = true
		case strings.TrimSpace(part) != "":
			kept = append(kept, part)
		}
	}
	if !removed {
		return nil
	}
	return writeUserPath(strings.Join(kept, ";"), typ)
}

// broadcastEnvChange tells Explorer/shells that PATH changed so NEW
// terminals pick it up without logging off.
func broadcastEnvChange() {
	env, err := windows.UTF16PtrFromString("Environment")
	if err != nil {
		return
	}
	const hwndBroadcast, wmSettingChange, smtoAbortIfHung = 0xffff, 0x1a, 0x0002
	p := windows.NewLazySystemDLL("user32.dll").NewProc("SendMessageTimeoutW")
	_, _, _ = p.Call(hwndBroadcast, wmSettingChange, 0, uintptr(unsafe.Pointer(env)), smtoAbortIfHung, 5000, 0)
}
